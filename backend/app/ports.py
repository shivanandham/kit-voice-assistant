"""Provider seams (ports): the external services the app depends on, as small Protocols.

Each Protocol lists only the methods the application actually calls. Today every port has
exactly one adapter; a second provider is added by writing a class (or module) with the same
methods and passing it in at the injection point named in the docstring. Nothing else in the
app has to change. backend/tests/test_ports_conformance.py checks the current adapters still
satisfy these Protocols, so the seams are enforced rather than only documented.
"""

from __future__ import annotations

from collections.abc import AsyncIterator
from typing import Protocol, runtime_checkable

from app.voice.deepgram import SttEvent


@runtime_checkable
class SpeechToText(Protocol):
    """Streaming speech-to-text for one voice socket.

    Adapter today: app.voice.deepgram.DeepgramSTT (Deepgram live WebSocket).
    Second provider: implement these methods (optionally ``finalize()``, which the session
    calls when present) and pass a factory as ``stt_factory`` to app.voice.session.build_router.
    """

    async def send_audio(self, pcm: bytes) -> None: ...
    def events(self) -> AsyncIterator[SttEvent]: ...
    async def close(self) -> None: ...


@runtime_checkable
class TextToSpeech(Protocol):
    """Sentence-at-a-time speech synthesis for one voice socket.

    Adapter today: app.voice.deepgram.DeepgramTTS (Deepgram Aura speak WebSocket, REST fallback).
    Second provider: implement these methods and pass a factory as ``tts_factory`` to
    app.voice.session.build_router.
    """

    async def warm(self) -> None: ...
    def synthesize(self, text: str) -> AsyncIterator[bytes]: ...
    async def reset(self) -> None: ...
    async def close(self) -> None: ...


@runtime_checkable
class ChatModel(Protocol):
    """Fallback chat model used when the primary LLM call fails.

    Adapter today: the app.agent.fallback module (Google Gemini), called as
    ``fallback.answer(system, messages)`` from app.agent.loop. Returns None on failure.
    Second provider: a module or object with the same ``answer`` coroutine.
    """

    async def answer(self, system: list[dict], messages: list[dict]) -> str | None: ...


@runtime_checkable
class Embedder(Protocol):
    """Text embedding for document search.

    Adapter today: app.knowledge.rag.embed_texts (Gemini embeddings, rate limited and
    normalised), used for both indexing ("RETRIEVAL_DOCUMENT") and queries ("RETRIEVAL_QUERY").
    Second provider: any coroutine function with this signature returning one vector per text.
    """

    async def __call__(self, texts: list[str], task_type: str) -> list[list[float]]: ...


@runtime_checkable
class CollegeSystem(Protocol):
    """The college's system of record (public info, student, teacher and placement data).

    Adapter today: app.kit.client.KitClient (HTTP client for the KIT API, one per token).
    Second provider: a class with these coroutines raising app.kit.client.KitError on failure.
    """

    async def health(self) -> dict: ...
    async def today(self) -> dict: ...
    async def college(self) -> dict: ...
    async def courses(self) -> list[dict]: ...
    async def documents(self) -> list[dict]: ...
    async def document_file(self, id: int) -> bytes: ...
    async def submit_admission(self, payload: dict, idempotency_key: str) -> dict: ...
    async def login(self, login_id: str, password: str) -> dict: ...
    async def placement_drives(self) -> list[dict]: ...
    async def me(self) -> dict: ...
    async def academics(self) -> dict: ...
    async def subjects(self) -> list[dict]: ...
    async def timetable(self) -> list[dict]: ...
    async def calendar(
        self, from_date: str | None = None, to_date: str | None = None
    ) -> list[dict]: ...
    async def attendance(self) -> dict: ...
    async def attendance_sessions(
        self, subject: str | None = None, from_date: str | None = None, to_date: str | None = None
    ) -> list[dict]: ...
    async def my_requests(self) -> list[dict]: ...
    async def create_request(self, payload: dict, idempotency_key: str) -> dict: ...
    async def get_request(self, id: int) -> dict: ...
    async def cancel_request(self, id: int, idempotency_key: str | None = None) -> dict: ...
    async def register_drive(self, id: int, idempotency_key: str | None = None) -> dict: ...
    async def my_placements(self) -> list[dict]: ...
    async def teacher_classes(self) -> list[dict]: ...
    async def teacher_requests(self, status: str | None = None) -> list[dict]: ...
    async def class_attendance(self, class_id: int) -> dict: ...
    async def approve_request(
        self, id: int, comment: str | None = None, idempotency_key: str | None = None
    ) -> dict: ...
    async def reject_request(
        self, id: int, reason: str, idempotency_key: str | None = None
    ) -> dict: ...
